import { UGCPGraph } from "@/models/ugcp/schema";
import { useTerraformStore } from "@/store/useTerraformStore";
import { useDiagramStore } from "@/store/useDiagramStore";
import { toUGCPGraph } from "@/lib/ugcp/graphSync";

export interface ExportOptions {
  format: "single" | "module";
  includeProvider?: boolean;
  includeVariables?: boolean;
  includeOutputs?: boolean;
  moduleName?: string;
}

export interface TerraformModule {
  "main.tf": string;
  "variables.tf"?: string;
  "outputs.tf"?: string;
  "provider.tf"?: string;
  "versions.tf"?: string;
}

/**
 * Generates a complete Terraform configuration from the current diagram state
 */
export function generateTerraformConfig(
  graph: UGCPGraph,
  terraformBlocks: Record<string, string>,
  options: ExportOptions = { format: "single" }
): string | TerraformModule {
  const { format, includeProvider = true, includeVariables = true, includeOutputs = true, moduleName = "infraflow" } = options;

  // Collect all terraform blocks from the store
  const blocks = Object.values(terraformBlocks);

  if (format === "single") {
    return generateSingleFile(blocks, includeProvider, includeVariables, includeOutputs);
  } else {
    return generateModuleStructure(blocks, includeProvider, includeVariables, includeOutputs, moduleName);
  }
}

/**
 * Generates a single .tf file with all resources
 */
function generateSingleFile(
  blocks: string[],
  includeProvider: boolean,
  includeVariables: boolean,
  includeOutputs: boolean
): string {
  const parts: string[] = [];

  // Header comment
  parts.push(`# Terraform configuration generated by InfraFlow`);
  parts.push(`# Generated at: ${new Date().toISOString()}`);
  parts.push("");

  // Provider configuration
  if (includeProvider) {
    parts.push(generateProviderBlock());
    parts.push("");
  }

  // Variables
  if (includeVariables) {
    parts.push(generateVariablesBlock());
    parts.push("");
  }

  // Resource blocks
  if (blocks.length > 0) {
    parts.push("# Resources");
    parts.push("");
    parts.push(blocks.join("\n\n"));
    parts.push("");
  }

  // Outputs
  if (includeOutputs) {
    parts.push(generateOutputsBlock(blocks));
  }

  return parts.join("\n");
}

/**
 * Generates a module structure with separate files
 */
function generateModuleStructure(
  blocks: string[],
  includeProvider: boolean,
  includeVariables: boolean,
  includeOutputs: boolean,
  moduleName: string
): TerraformModule {
  const moduleStructure: TerraformModule = {
    "main.tf": "",
    "variables.tf": "",
    "outputs.tf": "",
    "provider.tf": "",
    "versions.tf": "",
  };

  // versions.tf
  moduleStructure["versions.tf"] = generateVersionsBlock();

  // provider.tf
  if (includeProvider) {
    moduleStructure["provider.tf"] = generateProviderBlock();
  }

  // variables.tf
  if (includeVariables) {
    moduleStructure["variables.tf"] = generateVariablesBlock();
  }

  // main.tf - resources
  const resourceParts: string[] = [
    `# ${moduleName} - Main configuration`,
    `# Generated at: ${new Date().toISOString()}`,
    "",
  ];

  if (blocks.length > 0) {
    resourceParts.push("# Resources");
    resourceParts.push("");
    resourceParts.push(blocks.join("\n\n"));
  }

  moduleStructure["main.tf"] = resourceParts.join("\n");

  // outputs.tf
  if (includeOutputs) {
    moduleStructure["outputs.tf"] = generateOutputsBlock(blocks);
  }

  return moduleStructure;
}

/**
 * Generates the Terraform required_version and required_providers block
 */
function generateVersionsBlock(): string {
  return `# Terraform version constraints
terraform {
  required_version = ">= 1.0"

  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
  }
}`;
}

/**
 * Generates the AWS provider block
 */
function generateProviderBlock(): string {
  return `# AWS Provider Configuration
provider "aws" {
  region = var.aws_region

  default_tags {
    tags = {
      ManagedBy = "InfraFlow"
      Environment = var.environment
    }
  }
}`;
}

/**
 * Generates common variables
 */
function generateVariablesBlock(): string {
  return `# Variables
variable "aws_region" {
  description = "AWS region for resources"
  type        = string
  default     = "us-east-1"
}

variable "environment" {
  description = "Environment name (dev, staging, prod)"
  type        = string
  default     = "dev"
}

variable "project_name" {
  description = "Project name for resource naming"
  type        = string
  default     = "infraflow"
}

variable "vpc_cidr" {
  description = "CIDR block for VPC"
  type        = string
  default     = "10.0.0.0/16"
}

variable "availability_zones" {
  description = "List of availability zones"
  type        = list(string)
  default     = ["us-east-1a", "us-east-1b"]
}`;
}

/**
 * Generates useful outputs based on resources
 */
function generateOutputsBlock(blocks: string[]): string {
  const outputs: string[] = [
    `# Outputs`,
    `# Generated at: ${new Date().toISOString()}`,
    ``,
  ];

  // Try to extract resource names from blocks for outputs
  const resourcePatterns = [
    { pattern: /resource\s+"aws_vpc"\s+"([^"]+)"/g, name: "vpc_id", type: "aws_vpc" },
    { pattern: /resource\s+"aws_subnet"\s+"([^"]+)"/g, name: "subnet_ids", type: "aws_subnet", isList: true },
    { pattern: /resource\s+"aws_instance"\s+"([^"]+)"/g, name: "instance_ids", type: "aws_instance", isList: true },
    { pattern: /resource\s+"aws_db_instance"\s+"([^"]+)"/g, name: "rds_endpoint", type: "aws_db_instance" },
    { pattern: /resource\s+"aws_s3_bucket"\s+"([^"]+)"/g, name: "bucket_names", type: "aws_s3_bucket", isList: true },
    { pattern: /resource\s+"aws_security_group"\s+"([^"]+)"/g, name: "security_group_ids", type: "aws_security_group", isList: true },
    { pattern: /resource\s+"aws_lb"\s+"([^"]+)"/g, name: "alb_dns_name", type: "aws_lb" },
    { pattern: /resource\s+"aws_iam_role"\s+"([^"]+)"/g, name: "iam_role_arns", type: "aws_iam_role", isList: true },
  ];

  const addedOutputs = new Set<string>();

  for (const { pattern, name, type, isList } of resourcePatterns) {
    let match;
    const resources: string[] = [];

    // Reset regex lastIndex
    pattern.lastIndex = 0;

    for (const block of blocks) {
      while ((match = pattern.exec(block)) !== null) {
        const resourceName = match[1];
        if (!resources.includes(resourceName)) {
          resources.push(resourceName);
        }
      }
    }

    if (resources.length > 0) {
      const outputName = `${type}_${name}`;
      if (!addedOutputs.has(outputName)) {
        addedOutputs.add(outputName);

        if (isList) {
          const refs = resources.map((r) => `${type}.${r}.id`).join(", ");
          outputs.push(`output "${outputName}" {`);
          outputs.push(`  description = "IDs of ${type} resources"`);
          outputs.push(`  value       = [${refs}]`);
          outputs.push(`}`);
        } else {
          const resourceName = resources[0];
          if (type === "aws_db_instance") {
            outputs.push(`output "${outputName}" {`);
            outputs.push(`  description = "RDS instance endpoint"`);
            outputs.push(`  value       = ${type}.${resourceName}.endpoint`);
            outputs.push(`}`);
          } else if (type === "aws_lb") {
            outputs.push(`output "${outputName}" {`);
            outputs.push(`  description = "Load balancer DNS name"`);
            outputs.push(`  value       = ${type}.${resourceName}.dns_name`);
            outputs.push(`}`);
          } else if (type === "aws_iam_role") {
            const refs = resources.map((r) => `${type}.${r}.arn`).join(", ");
            outputs.push(`output "${outputName}" {`);
            outputs.push(`  description = "IAM role ARNs"`);
            outputs.push(`  value       = [${refs}]`);
            outputs.push(`}`);
          } else {
            outputs.push(`output "${outputName}" {`);
            outputs.push(`  description = "${type} ID"`);
            outputs.push(`  value       = ${type}.${resourceName}.id`);
            outputs.push(`}`);
          }
        }
        outputs.push("");
      }
    }
  }

  return outputs.join("\n");
}

/**
 * Downloads a file in the browser
 */
export function downloadTerraformFile(
  content: string | TerraformModule,
  fileName: string = "infraflow.tf",
  format: "single" | "module" = "single"
) {
  if (format === "single") {
    const blob = new Blob([content as string], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = fileName;
    a.click();
    URL.revokeObjectURL(url);
  } else {
    // For module format, create a ZIP-like download (multiple files)
    const moduleContent = content as TerraformModule;
    Object.entries(moduleContent).forEach(([fileName, fileContent]) => {
      if (fileContent) {
        const blob = new Blob([fileContent], { type: "text/plain" });
        const url = URL.createObjectURL(blob);
        const a = document.createElement("a");
        a.href = url;
        a.download = fileName;
        a.click();
        URL.revokeObjectURL(url);
      }
    });
  }
}

/**
 * Gets the current diagram state as a UGCPGraph for export
 */
export function getDiagramAsGraph(): UGCPGraph {
  const { nodes, edges, projectId, projectName } = useDiagramStore.getState();

  return toUGCPGraph(nodes, edges, {
    id: projectId || "local",
    name: projectName || "Untitled Project",
  });
}

/**
 * Exports current project as Terraform
 */
export function exportCurrentProject(
  options: ExportOptions = { format: "single" }
) {
  const graph = getDiagramAsGraph();
  const terraformBlocks = useTerraformStore.getState().terraformBlocks;

  const result = generateTerraformConfig(graph, terraformBlocks, options);

  if (options.format === "single") {
    const fileName = `${graph.metadata.name.replace(/\s+/g, "-").toLowerCase()}.tf`;
    downloadTerraformFile(result as string, fileName, "single");
  } else {
    downloadTerraformFile(result as TerraformModule, "main.tf", "module");
  }
}