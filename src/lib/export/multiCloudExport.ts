"use client";

import { AnyNode } from "@/utils/types/resource";
import { Edge } from "@xyflow/react";

export type ExportFormat = "terraform" | "cloudformation" | "pulumi" | "kubernetes-helm" | "kubernetes-kustomize" | "bicep" | "arm";

export interface ExportOptions {
  format: ExportFormat;
  moduleStructure?: boolean;
  includeProvider?: boolean;
  includeBackend?: boolean;
  region?: string;
  environment?: string;
}

export interface ExportResult {
  files: Record<string, string>;
  mainFile: string;
  format: ExportFormat;
  explanation: string;
}

function getResourceType(node: AnyNode): string {
  return node.type ?? "unknown";
}

function getResourceName(node: AnyNode): string {
  const data = node.data as Record<string, unknown>;
  const explicitName = [data.Name, data.name, data.BucketName, data.TagName]
    .find((value): value is string => typeof value === "string" && value.trim().length > 0);
  return explicitName?.trim() || `${node.type || "resource"}_${node.id.slice(0, 8)}`;
}

function sanitizeName(name: string): string {
  const normalized = name.replace(/[^a-zA-Z0-9_-]/g, "_").toLowerCase();
  return /^[a-z_]/.test(normalized) ? normalized : `resource_${normalized}`;
}

function generateTerraform(nodes: AnyNode[], edges: Edge[], options: ExportOptions): ExportResult {
  const files: Record<string, string> = {};

  // versions.tf
  files["versions.tf"] = `terraform {
  required_version = ">= 1.0"
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
  }
}`;

  // providers.tf
  files["providers.tf"] = `provider "aws" {
  region = var.aws_region
}`;

  // variables.tf
  const variables = `variable "aws_region" {
  description = "AWS region"
  type        = string
  default     = "${options.region || "us-east-1"}"
}

variable "environment" {
  description = "Environment name"
  type        = string
  default     = "${options.environment || "dev"}"
}

variable "project_name" {
  description = "Project name"
  type        = string
  default     = "infraflow"
}`;

  // main.tf
  let mainTf = `# Generated by InfraFlow
# ${new Date().toISOString()}

locals {
  common_tags = {
    Environment = var.environment
    Project     = var.project_name
    ManagedBy   = "InfraFlow"
  }
}

`;

  const resourceMap = new Map<string, string>();

  nodes.forEach(node => {
    const type = getResourceType(node);
    const name = sanitizeName(getResourceName(node));
    const resourceKey = `${type}_${name}`;
    resourceMap.set(node.id, resourceKey);

    const data = node.data as Record<string, unknown>;
    mainTf += generateTerraformResource(type, name, data, node);
  });

  // Add dependencies based on edges
  edges.forEach(edge => {
    // Dependencies are implicit in Terraform via references
  });

  files["main.tf"] = mainTf;
  files["variables.tf"] = variables;

  // outputs.tf
  let outputs = `# Outputs\n`;
  nodes.forEach(node => {
    const type = getResourceType(node);
    const name = sanitizeName(getResourceName(node));
    const resourceKey = `${type}_${name}`;
    outputs += generateTerraformOutput(type, resourceKey);
  });
  files["outputs.tf"] = outputs;

  return {
    files,
    mainFile: "main.tf",
    format: "terraform",
    explanation: `Generated ${Object.keys(files).length} Terraform files for ${nodes.length} resources`
  };
}

function generateTerraformResource(type: string, name: string, data: Record<string, unknown>, node: AnyNode): string {
  const tags = `merge(local.common_tags, { Name = "${data.Name || name}" })`;

  switch (type) {
    case "vpc":
      return `resource "aws_vpc" "${name}" {
  cidr_block           = "${data.CIDR || "10.0.0.0/16"}"
  enable_dns_hostnames = ${data.EnableDNS === "yes" ? "true" : "false"}
  enable_dns_support   = true
  tags                 = ${tags}
}

`;

    case "subnet": {
      const parentVpcId = (data.parentVpcId as string) || "main";
      return `resource "aws_subnet" "${name}" {
  vpc_id                  = aws_vpc.${sanitizeName(parentVpcId)}.id
  cidr_block              = "${(data.CIDR as string) || "10.0.1.0/24"}"
  availability_zone       = "${(data.AvailabilityZone as string) || "us-east-1a"}"
  map_public_ip_on_launch = ${(data.MapPublicIpOnLaunch as string) === "yes" ? "true" : "false"}
  tags                    = ${tags}
}

`;
    }

    case "elb":
      return `resource "aws_lb" "${name}" {
  name               = "${data.Name || name}"
  internal           = ${data.Scheme === "internal" ? "true" : "false"}
  load_balancer_type = "application"
  security_groups    = []
  subnets            = []
  tags               = ${tags}
}

`;

    case "ec2":
      return `resource "aws_instance" "${name}" {
  ami                    = "${data.AMI || "ami-12345678"}"
  instance_type          = "${data.InstanceType || "t3.medium"}"
  vpc_security_group_ids = []
  subnet_id              = ""
  tags                   = ${tags}
}

`;

    case "rds":
      return `resource "aws_db_instance" "${name}" {
  identifier        = "${data.Name || name}"
  engine            = "${data.Engine || "postgres"}"
  instance_class    = "${data.InstanceClass || "db.t3.medium"}"
  allocated_storage = ${data.AllocatedStorage || 20}
  db_name           = "${data.DBName || "appdb"}"
  username          = "${data.MasterUsername || "admin"}"
  password          = "${data.MasterPassword || "changeme"}"
  skip_final_snapshot = true
  tags              = ${tags}
}

`;

    case "s3":
      return `resource "aws_s3_bucket" "${name}" {
  bucket = "${data.Name || name}"
  tags   = ${tags}
}

`;

    case "security-group":
      return `resource "aws_security_group" "${name}" {
  name        = "${data.Name || name}"
  description = "${data.Description || "Managed by InfraFlow"}"
  vpc_id      = ""
  tags        = ${tags}
}

`;

    case "internet-gateway": {
      const parentVpcId = (data.parentVpcId as string) || "main";
      return `resource "aws_internet_gateway" "${name}" {
  vpc_id = aws_vpc.${sanitizeName(parentVpcId)}.id
  tags   = ${tags}
}

`;
    }

    case "nat-gateway":
      return `resource "aws_nat_gateway" "${name}" {
  subnet_id     = ""
  allocation_id = ""
  tags          = ${tags}
}

`;

    default:
      return `# Resource type "${type}" not implemented\n`;
  }
}

