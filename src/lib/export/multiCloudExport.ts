function generatePulumiExport(type: string, name: string): string {
  const exports: Record<string, string> = {
    "vpc": `export const ${name}VpcId = ${name}Vpc.id;\nexport const ${name}VpcArn = ${name}Vpc.arn;\n`,
    "subnet": `export const ${name}SubnetId = ${name}Subnet.id;\n`,
    "elb": `export const ${name}AlbDnsName = ${name}Alb.dnsName;\nexport const ${name}AlbArn = ${name}Alb.arn;\n`,
    "ec2": `export const ${name}Ec2Id = ${name}Ec2.id;\nexport const ${name}Ec2PublicIp = ${name}Ec2.publicIp;\n`,
    "rds": `export const ${name}RdsEndpoint = ${name}Rds.endpoint;\nexport const ${name}RdsArn = ${name}Rds.arn;\n`,
    "s3": `export const ${name}BucketArn = ${name}Bucket.arn;\nexport const ${name}BucketDomainName = ${name}Bucket.bucketDomainName;\n`,
    "security-group": `export const ${name}SgId = ${name}Sg.id;\n`,
    "internet-gateway": `export const ${name}IgwId = ${name}Igw.id;\n`,
    "nat-gateway": `export const ${name}NatId = ${name}Nat.id;\n`,
  };
  return exports[type] || "";
}

function generateKubernetesHelm(nodes: AnyNode[], edges: Edge[], options: ExportOptions): ExportResult {
  const files: Record<string, string> = {};

  // Chart.yaml
  files["Chart.yaml"] = `apiVersion: v2
name: infraflow-${options.environment || "dev"}
description: Infrastructure generated by InfraFlow
type: application
version: 0.1.0
appVersion: "1.0.0"
`;

  // values.yaml
  const values = `# Default values for infraflow chart
replicaCount: 1

image:
  repository: nginx
  pullPolicy: IfNotPresent
  tag: "latest"

service:
  type: ClusterIP
  port: 80

resources: {}

nodeSelector: {}

tolerations: []

affinity: {}
`;
  files["values.yaml"] = values;

  // templates/deployment.yaml
  const deployment = `apiVersion: apps/v1
kind: Deployment
metadata:
  name: {{ .Release.Name }}-app
  labels:
    {{- include "infraflow.labels" . | nindent 4 }}
spec:
  replicas: {{ .Values.replicaCount }}
  selector:
    matchLabels:
      {{- include "infraflow.selectorLabels" . | nindent 6 }}
  template:
    metadata:
      labels:
        {{- include "infraflow.selectorLabels" . | nindent 8 }}
    spec:
      containers:
        - name: {{ .Chart.Name }}
          image: "{{ .Values.image.repository }}:{{ .Values.image.tag | default .Chart.AppVersion }}"
          imagePullPolicy: {{ .Values.image.pullPolicy }}
          ports:
            - name: http
              containerPort: 80
              protocol: TCP
          resources:
            {{- toYaml .Values.resources | nindent 12 }}
      {{- with .Values.nodeSelector }}
      nodeSelector:
        {{- toYaml . | nindent 8 }}
      {{- end }}
      {{- with .Values.affinity }}
      affinity:
        {{- toYaml . | nindent 8 }}
      {{- end }}
      {{- with .Values.tolerations }}
      tolerations:
        {{- toYaml . | nindent 8 }}
      {{- end }}
`;
  files["templates/deployment.yaml"] = deployment;

  // templates/service.yaml
  files["templates/service.yaml"] = `apiVersion: v1
kind: Service
metadata:
  name: {{ .Release.Name }}-service
  labels:
    {{- include "infraflow.labels" . | nindent 4 }}
spec:
  type: {{ .Values.service.type }}
  ports:
    - port: {{ .Values.service.port }}
      targetPort: http
      protocol: TCP
      name: http
  selector:
    {{- include "infraflow.selectorLabels" . | nindent 4 }}
`;

  // templates/_helpers.tpl
  files["templates/_helpers.tpl"] = `{{/*
Expand the name of the chart.
*/}}
{{- define "infraflow.name" -}}
{{- default .Chart.Name .Values.nameOverride | trunc 63 | trimSuffix "-" }}
{{- end }}

{{/*
Create a default fully qualified app name.
*/}}
{{- define "infraflow.fullname" -}}
{{- if .Values.fullnameOverride }}
{{- .Values.fullnameOverride | trunc 63 | trimSuffix "-" }}
{{- else }}
{{- $name := default .Chart.Name .Values.nameOverride }}
{{- if contains $name .Release.Name }}
{{- .Release.Name | trunc 63 | trimSuffix "-" }}
{{- else }}
{{- printf "%s-%s" .Release.Name $name | trunc 63 | trimSuffix "-" }}
{{- end }}
{{- end }}
{{- end }}

{{/*
Create chart name and version as used by the chart label.
*/}}
{{- define "infraflow.chart" -}}
{{- printf "%s-%s" .Chart.Name .Chart.Version | replace "+" "_" | trunc 63 | trimSuffix "-" }}
{{- end }}

{{/*
Common labels
*/}}
{{- define "infraflow.labels" -}}
helm.sh/chart: {{ include "infraflow.chart" . }}
{{ include "infraflow.selectorLabels" . }}
{{- end }}

{{/*
Selector labels
*/}}
{{- define "infraflow.selectorLabels" -}}
app.kubernetes.io/name: {{ include "infraflow.name" . }}
app.kubernetes.io/instance: {{ .Release.Name }}
app.kubernetes.io/version: {{ .Chart.AppVersion }}
app.kubernetes.io/managed-by: {{ .Release.Service }}
{{- end }}
`;

  return {
    files,
    mainFile: "Chart.yaml",
    format: "kubernetes-helm",
    explanation: `Generated Helm chart with ${Object.keys(files).length} template files`
  };
}

function generateKubernetesKustomize(nodes: AnyNode[], edges: Edge[], options: ExportOptions): ExportResult {
  const files: Record<string, string> = {};

  // kustomization.yaml
  files["kustomization.yaml"] = `apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization

namespace: ${options.environment || "dev"}

resources:
  - deployment.yaml
  - service.yaml

commonLabels:
  app.kubernetes.io/name: infraflow
  app.kubernetes.io/instance: ${options.environment || "dev"}
  app.kubernetes.io/managed-by: InfraFlow
  app.kubernetes.io/part-of: infraflow

configMapGenerator:
  - name: infraflow-config
    literals:
      - ENVIRONMENT=${options.environment || "dev"}
      - PROJECT_NAME=infraflow
`;

  // deployment.yaml
  files["deployment.yaml"] = `apiVersion: apps/v1
kind: Deployment
metadata:
  name: infraflow-app
  labels:
    app: infraflow
spec:
  replicas: 1
  selector:
    matchLabels:
      app: infraflow
  template:
    metadata:
      labels:
        app: infraflow
    spec:
      containers:
        - name: app
          image: nginx:latest
          ports:
            - containerPort: 80
          envFrom:
            - configMapRef:
                name: infraflow-config
`;

  // service.yaml
  files["service.yaml"] = `apiVersion: v1
kind: Service
metadata:
  name: infraflow-service
  labels:
    app: infraflow
spec:
  type: ClusterIP
  ports:
    - port: 80
      targetPort: 80
  selector:
    app: infraflow
`;

  return {
    files,
    mainFile: "kustomization.yaml",
    format: "kubernetes-kustomize",
    explanation: `Generated Kustomize configuration with ${Object.keys(files).length} files`
  };
}

function generateBicep(nodes: AnyNode[], edges: Edge[], options: ExportOptions): ExportResult {
  let code = `// Generated by InfraFlow
// ${new Date().toISOString()}

@description('Azure region')
param location string = '${options.region || "eastus"}'

@description('Environment name')
param environment string = '${options.environment || "dev"}'

@description('Project name')
param projectName string = 'infraflow'

var commonTags = {
  Environment: environment
  Project: projectName
  ManagedBy: 'InfraFlow'
}

`;

  nodes.forEach(node => {
    const type = getResourceType(node);
    const name = sanitizeName(getResourceName(node));
    const data = node.data as Record<string, unknown>;
    code += generateBicepResource(type, name, data);
  });

  code += "\n// Outputs\n";
  nodes.forEach(node => {
    const type = getResourceType(node);
    const name = sanitizeName(getResourceName(node));
    code += generateBicepOutput(type, name);
  });

  return {
    files: { "main.bicep": code },
    mainFile: "main.bicep",
    format: "bicep",
    explanation: `Generated Bicep template for ${nodes.length} resources`
  };
}

function generateBicepResource(type: string, name: string, data: Record<string, unknown>): string {
  const tags = `commonTags`;

  switch (type) {
    case "vpc":
      return `resource ${name}Vnet 'Microsoft.Network/virtualNetworks@2023-09-01' = {
  name: '${data.Name || name}'
  location: location
  tags: ${tags}
  properties: {
    addressSpace: {
      addressPrefixes: ['${data.CIDR || "10.0.0.0/16"}']
    }
  }
}

`;

    case "subnet": {
      const parentVpcId = (data.parentVpcId as string) || "main";
      return `resource ${name}Subnet 'Microsoft.Network/virtualNetworks/subnets@2023-09-01' = {
  name: '${data.Name || name}'
  parent: ${sanitizeName(parentVpcId)}Vnet
  properties: {
    addressPrefix: '${(data.CIDR as string) || "10.0.1.0/24"}'
  }
}

`;
    }

    case "elb":
      return `// Azure Load Balancer (Application Gateway)
resource ${name}AppGw 'Microsoft.Network/applicationGateways@2023-09-01' = {
  name: '${data.Name || name}'
  location: location
  tags: ${tags}
  sku: {
    name: 'Standard_v2'
    tier: 'Standard_v2'
  }
  properties: {
    // Configuration would go here
  }
}

`;

    case "ec2": {
      const instanceType = (data.InstanceType as string) || "t3.medium";
      return `// Azure Virtual Machine
resource ${name}Vm 'Microsoft.Compute/virtualMachines@2023-09-01' = {
  name: '${data.Name || name}'
  location: location
  tags: ${tags}
  properties: {
    hardwareProfile: {
      vmSize: '${mapEc2ToAzure(instanceType)}'
    }
    storageProfile: {
      imageReference: {
        publisher: 'Canonical'
        offer: 'UbuntuServer'
        sku: '18.04-LTS'
        version: 'latest'
      }
    }
    osProfile: {
      computerName: '${name}'
      adminUsername: 'azureuser'
    }
    networkProfile: {
      networkInterfaces: []
    }
  }
}

`;
    }

    case "rds":
      return `// Azure Database for PostgreSQL
resource ${name}Db 'Microsoft.DBforPostgreSQL/flexibleServers@2023-09-01' = {
  name: '${data.Name || name}'
  location: location
  tags: ${tags}
  sku: {
    name: 'Standard_B1ms'
    tier: 'Burstable'
  }
  properties: {
    administratorLogin: '${data.MasterUsername || "admin"}'
    administratorLoginPassword: '${data.MasterPassword || "changeme"}'
    version: '14'
    storage: {
      storageSizeGB: ${data.AllocatedStorage || 20}
    }
  }
}

`;

    case "s3": {
      const storageName = ((data.Name as string) || name).replace(/[^a-z0-9]/g, "").toLowerCase();
      return `// Azure Storage Account
resource ${name}Storage 'Microsoft.Storage/storageAccounts@2023-09-01' = {
  name: '${storageName}'
  location: location
  tags: ${tags}
  sku: {
    name: 'Standard_LRS'
  }
  kind: 'StorageV2'
  properties: {
    accessTier: 'Hot'
  }
}

`;
    }

    default:
      return `// Resource type "${type}" not implemented for Bicep\n`;
  }
}

function mapEc2ToAzure(instanceType: string): string {
  const mapping: Record<string, string> = {
    "t3.micro": "Standard_B1ls",
    "t3.small": "Standard_B1s",
    "t3.medium": "Standard_B2s",
    "t3.large": "Standard_B4ms",
    "t3.xlarge": "Standard_B8ms",
    "m5.large": "Standard_D4s_v3",
    "m5.xlarge": "Standard_D8s_v3",
    "m5.2xlarge": "Standard_D16s_v3",
  };
  return mapping[instanceType] || "Standard_B2s";
}

function generateBicepOutput(type: string, name: string): string {
  const outputs: Record<string, string> = {
    "vpc": `output ${name}VnetId string = ${name}Vnet.id\noutput ${name}VnetName string = ${name}Vnet.name\n`,
    "subnet": `output ${name}SubnetId string = ${name}Subnet.id\n`,
    "elb": `output ${name}AppGwId string = ${name}AppGw.id\noutput ${name}AppGwName string = ${name}AppGw.name\n`,
    "ec2": `output ${name}VmId string = ${name}Vm.id\noutput ${name}VmName string = ${name}Vm.name\n`,
    "rds": `output ${name}DbId string = ${name}Db.id\noutput ${name}DbFqdn string = ${name}Db.properties.fullyQualifiedDomainName\n`,
    "s3": `output ${name}StorageId string = ${name}Storage.id\noutput ${name}StorageName string = ${name}Storage.name\n`,
  };
  return outputs[type] || "";
}

function generateARM(nodes: AnyNode[], edges: Edge[], options: ExportOptions): ExportResult {
  const resources: any[] = [];
  const parameters: Record<string, any> = {
    location: { type: "String", defaultValue: options.region || "eastus" },
    environment: { type: "String", defaultValue: options.environment || "dev" },
    projectName: { type: "String", defaultValue: "infraflow" }
  };

  nodes.forEach(node => {
    const type = getResourceType(node);
    const name = sanitizeName(getResourceName(node));
    const data = node.data as Record<string, unknown>;
    const resource = generateARMResource(type, name, data);
    if (resource) resources.push(resource);
  });

  const template = {
    $schema: "https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#",
    contentVersion: "1.0.0.0",
    parameters,
    variables: {
      commonTags: {
        Environment: "[parameters('environment')]",
        Project: "[parameters('projectName')]",
        ManagedBy: "InfraFlow"
      }
    },
    resources,
    outputs: generateARMOutputs(resources)
  };

  return {
    files: { "azuredeploy.json": JSON.stringify(template, null, 2) },
    mainFile: "azuredeploy.json",
    format: "arm",
    explanation: `Generated ARM template with ${resources.length} resources`
  };
}

function generateARMResource(type: string, name: string, data: Record<string, unknown>): any | null {
  const tags = "[variables('commonTags')]";

  switch (type) {
    case "vpc":
      return {
        type: "Microsoft.Network/virtualNetworks",
        apiVersion: "2023-09-01",
        name: data.Name as string || name,
        location: "[parameters('location')]",
        tags: tags,
        properties: {
          addressSpace: {
            addressPrefixes: [data.CIDR || "10.0.0.0/16"]
          }
        }
      };
    case "subnet":
      return {
        type: "Microsoft.Network/virtualNetworks/subnets",
        apiVersion: "2023-09-01",
        name: data.Name as string || name,
        dependsOn: ["[resourceId('Microsoft.Network/virtualNetworks', variables('vnetName'))]"],
        properties: {
          addressPrefix: data.CIDR || "10.0.1.0/24"
        }
      };
    case "s3":
      return {
        type: "Microsoft.Storage/storageAccounts",
        apiVersion: "2023-09-01",
        name: "[toLower(replace(parameters('projectName'), '-', ''))]",
        location: "[parameters('location')]",
        tags: tags,
        sku: { name: "Standard_LRS" },
        kind: "StorageV2",
        properties: { accessTier: "Hot" }
      };
    default:
      return null;
  }
}

function generateARMOutputs(resources: any[]): Record<string, any> {
  const outputs: Record<string, any> = {};
  resources.forEach(resource => {
    if (resource.type === "Microsoft.Network/virtualNetworks") {
      outputs[`${resource.name}Id`] = { type: "String", value: "[resourceId('Microsoft.Network/virtualNetworks', parameters('projectName'))]" };
    }
  });
  return outputs;
}

export function exportDiagram(nodes: AnyNode[], edges: Edge[], options: ExportOptions): ExportResult {
  switch (options.format) {
    case "terraform":
      return generateTerraform(nodes, edges, options);
    case "cloudformation":
      return generateCloudFormation(nodes, edges, options);
    case "pulumi":
      return generatePulumi(nodes, edges, options);
    case "kubernetes-helm":
      return generateKubernetesHelm(nodes, edges, options);
    case "kubernetes-kustomize":
      return generateKubernetesKustomize(nodes, edges, options);
    case "bicep":
      return generateBicep(nodes, edges, options);
    case "arm":
      return generateARM(nodes, edges, options);
    default:
      throw new Error(`Unsupported export format: ${options.format}`);
  }
}

